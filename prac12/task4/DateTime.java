package prac12.task4;

public class DateTime {

    public int day;
    public int month;
    public int year;
    public int hours;
    public int minutes;
    public int seconds;

    public DateTime(int day, int month, int year, int hours, int minutes, int seconds) {
        this.day = day;
        this.month = month;
        this.year = year;
        this.hours = hours;
        this.minutes = minutes;
        this.seconds = seconds;
    }
}
